export const getTranslation = (language: string = LANGUAGES.EN): TranslationDictionary => {
  const code = (language as LanguageCode) || LANGUAGES.EN;
  return translations[code] || translations[LANGUAGES.EN];
};

export const t = (key: string, language: string = LANGUAGES.EN): string => {
  const code = (language as LanguageCode) || LANGUAGES.EN;
  const langPack = translations[code] || translations[LANGUAGES.EN];
  const fallback = translations[LANGUAGES.EN];

  return langPack[key] || fallback[key] || key;
};

